#!/usr/bin/env python3
"""Generate src/markdown_entities.cyr, the HTML5 named character references (1.9.0).

The source of truth is Python's stdlib `html.entities.html5`, the WHATWG table
CommonMark points to ("Entity references consist of & + any of the valid HTML5
entity names + ;"). Only the names ending in `;` are kept: CommonMark does not
recognize the legacy forms written without one.

Each record is `name:CCCCCC[CCCCCC]` and a newline: the name without its `;`,
then one or two code points as six hex digits. Records are sorted by name and
split into string literals of RECS records each, like the stdlib's Unicode
data, and _md_ent_piece(i) returns piece i. The lookup lives in
src/markdown.cyr.

CI regenerates the file and requires no change.

Regenerate with:  python3 scripts/gen-md-entities.py src/markdown_entities.cyr
"""
import html.entities
import sys

RECS = 120


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/markdown_entities.cyr"
    table = sorted((k[:-1], v) for k, v in html.entities.html5.items() if k.endswith(";"))
    for name, value in table:
        assert name.isalnum() and name.isascii(), name
        assert 1 <= len(value) <= 2, (name, value)
    recs = [name + ":" + "".join(f"{ord(c):06X}" for c in value) + "\\n" for name, value in table]
    pieces = [recs[i:i + RECS] for i in range(0, len(recs), RECS)]
    lines = [
        "# markdown_entities.cyr — the HTML5 named character references, for src/markdown.cyr.",
        "#",
        "# GENERATED by scripts/gen-md-entities.py from Python's html.entities.html5 (the WHATWG",
        "# table CommonMark names). Do not edit by hand; CI regenerates it and requires no change.",
        f"# {len(table)} names that end in `;`, sorted. Each record is `name:CCCCCC[CCCCCC]` and a",
        "# newline: the name without its `;`, then one or two code points as six hex digits.",
        "",
        f"var _MD_ENT_COUNT = {len(table)};",
        f"var _MD_ENT_PIECES = {len(pieces)};",
        "",
    ]
    for i, piece in enumerate(pieces):
        lines.append(f"var _MD_ENT_{i} = \"" + "".join(piece) + "\";"
                     "  #skip-lint: generated data table, one literal, not wrappable")
    lines += ["", "# Piece i of the table, or 0 past the last.", "fn _md_ent_piece(i): i64 {"]
    for i in range(len(pieces)):
        lines.append(f"    if (i == {i}) {{ return _MD_ENT_{i}; }}")
    lines += ["    return 0;", "}", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out} ({len(table)} entities in {len(pieces)} pieces)")


if __name__ == "__main__":
    main()
